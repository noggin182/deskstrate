#!/usr/bin/env python3
"""Renders the deck's logo icons (firmware/deck/icons/*.svg) into LVGL alpha-only images
(firmware/deck/src/icons.c). Only coverage is kept: the deck tints each icon with
img_recolor, so one mask serves any colour and the edges stay anti-aliased.

Each SVG is rendered at 8x its on-screen size and box-filtered down, so every pixel's
alpha is the fraction of it the shape covers. Sizes are picked to keep straight edges
on pixel boundaries (the Windows panes are 9 px with a 1 px gap).

    pip install cairosvg pillow
    tools/render_icons.py
"""
import io
from pathlib import Path

import cairosvg
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
ICONS = ROOT / "firmware/deck/icons"
OUT = ROOT / "firmware/deck/src/icons.c"
SUPERSAMPLE = 8

# name: (svg, width, height)
SIZES = {
    "windows": ("windows.svg", 19, 19),
    "apple": ("apple.svg", 18, 22),
}


def render(svg: Path, width: int, height: int) -> bytes:
    png = cairosvg.svg2png(url=str(svg), output_width=width * SUPERSAMPLE, output_height=height * SUPERSAMPLE)
    alpha = Image.open(io.BytesIO(png)).convert("RGBA").getchannel("A")
    return alpha.resize((width, height), Image.BOX).tobytes()


def main() -> None:
    out = [
        "// Generated by tools/render_icons.py from firmware/deck/icons/*.svg. Do not edit.",
        '#include "icons.h"',
        "",
    ]
    for name, (svg, width, height) in SIZES.items():
        data = render(ICONS / svg, width, height)
        out.append(f"static const uint8_t {name}_alpha[{len(data)}] = {{")
        for row in range(height):
            line = data[row * width:(row + 1) * width]
            out.append("    " + ", ".join(f"0x{b:02X}" for b in line) + ",")
        out.append("};")
        out.append("")
        out.append(f"const lv_img_dsc_t icon_{name} = {{")
        out.append(f"    .header = {{.cf = LV_IMG_CF_ALPHA_8BIT, .always_zero = 0, .reserved = 0, .w = {width}, .h = {height}}},")
        out.append(f"    .data_size = sizeof({name}_alpha),")
        out.append(f"    .data = {name}_alpha,")
        out.append("};")
        out.append("")
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
